const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const browserName = process.env.BROWSER || 'chromium';
const browserType = require('playwright')[browserName];
const port = Number(process.env.TEST_PORT || 4202);
const base = `http://127.0.0.1:${port}`;
const server = spawn(process.execPath, ['tools/serve.mjs'], { env: { ...process.env, PORT: String(port) }, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true });
let browser;
(async () => {
  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.stdout.once('data', resolve);
    server.stderr.once('data', d => reject(Error(String(d))));
  });
  browser = await browserType.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.install();
  await page.goto(base + '/demos/ai-bot/Agent%20Bot.html');
  await page.locator('#bot-composer').waitFor();
  assert.ok(await page.locator('#bot-thread [data-sui-message]').count() >= 10, 'Long example conversation is available');
  await page.setViewportSize({ width: 1920, height: 1000 });
  const reading = await page.locator('.bot-conversation-layout').evaluate(node => {
    const own = node.getBoundingClientRect(), main = node.closest('.sb-main').getBoundingClientRect();
    return { width: own.width, leftMargin: own.left - main.left, rightMargin: main.right - own.right };
  });
  assert.ok(reading.width <= 1200 && reading.leftMargin > 100 && Math.abs(reading.leftMargin - reading.rightMargin) <= 1);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.waitForFunction(() => [...document.querySelectorAll('#bot-sidebar [data-bot-agent] img')].every(image => image.complete && image.naturalWidth > 0));
  assert.equal(await page.locator('#bot-sidebar [data-bot-agent] img').count(), 3);
  assert.equal(await page.locator('#bot-chat-tabs [role="tab"] img').count(), 1);
  assert.equal(await page.locator('select[name="bot-thread"]').count(), 0);
  await page.getByRole('tab', { name: 'Atlas', exact: true }).waitFor();
  const launchGroup = page.locator('[data-tree-key="bot-group-launch"]');
  await launchGroup.click();
  assert.equal(await launchGroup.getAttribute('aria-expanded'), 'false');
  await page.reload();
  await page.locator('#bot-composer').waitFor();
  assert.equal(await launchGroup.getAttribute('aria-expanded'), 'false');
  await launchGroup.focus();
  await page.keyboard.press('Enter');
  assert.equal(await launchGroup.getAttribute('aria-expanded'), 'true');
  const geometry = await page.evaluate(() => {
    const sidebar = document.getElementById('bot-sidebar').getBoundingClientRect();
    const main = document.querySelector('.sb-main').getBoundingClientRect();
    return { sidebarRight: sidebar.right, mainLeft: main.left, composerHeight: document.getElementById('bot-composer').getBoundingClientRect().height };
  });
  assert.ok(geometry.sidebarRight <= geometry.mainLeft + 1, 'Sidebar must not cover the conversation or composer');
  assert.ok(geometry.composerHeight <= 60, 'Compact composer should be a single message bar');
  assert.equal(await page.locator('#bot-compact-sidebar [data-shell-toggle]').count(), 0);
  await page.locator('#bot-compact-sidebar').hover();
  await page.clock.runFor(600);
  assert.equal(await page.locator('#bot-shell').evaluate(n => n.classList.contains('is-peeking')), false);
  assert.equal(Math.round((await page.locator('#bot-compact-sidebar').boundingBox()).width), 48);
  await page.evaluate(() => { window.originalSidebar = document.getElementById('bot-sidebar'); window.originalShell = document.getElementById('bot-shell'); });
  const choose = async (name, label) => {
    const group = page.locator('[data-sui-select]').filter({ has: page.locator(`select[name="${name}"]`) });
    await group.locator('[aria-haspopup="listbox"]').click();
    await page.getByRole('option', { name: label, exact: true }).click();
  };
  const send = async text => {
    await page.locator('#bot-composer textarea').fill(text);
    await page.locator('#bot-composer [data-send]').click();
    await page.locator('#bot-composer [data-composer-stop]').waitFor();
  };
  await page.getByRole('button', { name: 'Choose a prompt', exact: true }).click();
  await page.getByRole('button', { name: 'Compare competitor pricing', exact: true }).click();
  await page.getByRole('heading', { name: 'Scout', exact: true }).waitFor();
  await page.clock.runFor(4000);
  await page.getByRole('table', { name: 'Sample comparison', exact: true }).waitFor();
  const runLayout = await page.locator('.bot-agent-turn').first().evaluate(turn => {
    const run = turn.querySelector('[data-sui-agent-run]').getBoundingClientRect();
    const bubble = turn.querySelector('.sx-agent-message > .bubble').getBoundingClientRect();
    return { runWidth: run.width, bubbleWidth: bubble.width, gap: bubble.top - run.bottom };
  });
  assert.ok(Math.abs(runLayout.runWidth - runLayout.bubbleWidth) <= 1, 'Run width follows its response bubble');
  assert.ok(runLayout.gap >= 0 && runLayout.gap <= 8, 'Run and response belong together');
  await page.getByRole('button', { name: 'Preview competitor-brief.md' }).click();
  await page.clock.runFor(300);
  assert.match(await page.locator('.bot-preview').innerText(), /Northstar.*\$24/);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download brief', exact: true }).click();
  assert.equal((await downloadPromise).suggestedFilename(), 'competitor-brief.md');
  const researchRoute = new URL(page.url()).hash;
  await choose('bot-header-model', 'Fast · demo');
  await page.locator('#bot-composer textarea').fill('Keep this draft <img src=x onerror=alert(1)>');
  await page.reload();
  await page.locator('#bot-composer').waitFor();
  assert.match(await page.locator('#bot-composer textarea').inputValue(), /Keep this draft/);
  assert.equal(await page.locator('#bot-header select[name="bot-header-model"]').inputValue(), 'Fast');
  await send('Simulate a source failure');
  await page.clock.runFor(2500);
  await page.getByRole('button', { name: 'Retry response', exact: true }).click();
  await page.clock.runFor(2500);
  assert.equal(await page.getByRole('button', { name: 'Retry response', exact: true }).count(), 0);
  await send('Cancel this research');
  await page.getByRole('button', { name: 'Stop response', exact: true }).click();
  await page.clock.runFor(5000);
  assert.equal(await page.getByRole('button', { name: 'Retry response', exact: true }).count(), 1);
  await send('Work that will be interrupted');
  await page.reload();
  await page.getByRole('button', { name: 'Retry response', exact: true }).last().waitFor();
  assert.equal(await page.locator('[data-composer-stop]').count(), 0);

  const tasksButton = page.getByRole('button', { name: 'Tasks', exact: true });
  const chatRoute = new URL(page.url()).hash;
  await tasksButton.hover();
  await page.clock.runFor(1000);
  await page.getByRole('tooltip').filter({ hasText: /^Tasks$/ }).waitFor();
  await tasksButton.click();
  await tasksButton.focus();
  await page.keyboard.press('Enter');
  assert.equal(new URL(page.url()).hash, chatRoute);
  await page.locator('[data-bot-agent="forge"]').click();
  await page.getByRole('heading', { name: 'Forge', exact: true }).waitFor();
  await send('Prepare pricing update for approval');
  await page.clock.runFor(3000);
  await page.getByRole('button', { name: 'Approve sample change', exact: true }).click();
  assert.match(await page.locator('#bot-thread').innerText(), /demo plan now uses \$22/);
  const atlasRow = page.locator('[data-bot-agent="atlas"]');
  await atlasRow.click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Agent settings', exact: true }).click();
  assert.equal(await page.getByRole('region', { name: 'Agent settings', exact: true }).getByLabel(/^Name/).inputValue(), 'Atlas');
  await page.keyboard.press('Escape');
  await atlasRow.focus();
  await page.keyboard.press('Shift+F10');
  await page.getByRole('menuitem', { name: 'Delete agent', exact: true }).click();
  await page.getByText('Success delete agent', { exact: true }).waitFor();
  assert.equal(await page.locator('[data-bot-agent]').count(), 3);
  const settingsRoute = new URL(page.url()).hash;
  const savedDraft = await page.locator('#bot-composer textarea').inputValue();
  await page.getByRole('button', { name: 'Edit agent settings', exact: true }).click();
  const settingsPanel = page.getByRole('region', { name: 'Agent settings', exact: true });
  await settingsPanel.waitFor();
  assert.equal(await page.locator('#bot-edit-agent').isDisabled(), true);
  assert.equal(new URL(page.url()).hash, settingsRoute, 'Editing keeps the chat route');
  assert.equal(await page.locator('#bot-composer textarea').inputValue(), savedDraft);
  await settingsPanel.getByLabel(/^Name/).fill('Forge <sample>');
  await settingsPanel.getByLabel(/^Title/).fill('Launch builder');
  await settingsPanel.getByRole('button', { name: 'Instructions', exact: true }).click();
  await settingsPanel.getByLabel(/^Instructions/).fill('Keep the sample changes small.');
  await choose('agent-model', 'Thorough');
  await settingsPanel.getByRole('switch', { name: 'Compact replies', exact: true }).click();
  await settingsPanel.getByRole('button', { name: 'Save changes', exact: true }).click();
  assert.equal(await page.locator('[data-shell-detail]').count(), 0);
  await page.reload();
  await page.getByRole('button', { name: 'Edit agent settings', exact: true }).click();
  assert.equal(await settingsPanel.getByLabel(/^Name/).inputValue(), 'Forge <sample>');
  assert.equal(await settingsPanel.getByRole('switch', { name: 'Compact replies', exact: true }).getAttribute('aria-checked'), 'true');
  await settingsPanel.getByRole('button', { name: 'Close agent settings', exact: true }).click();
  await page.locator('[data-shell-detail]').waitFor({ state: 'detached' });
  assert.equal(await page.locator('#bot-edit-agent').isEnabled(), true);
  await page.getByRole('heading', { name: 'Forge <sample>', exact: true }).waitFor();
  await page.getByRole('button', { name: 'New thread', exact: true }).click();
  await page.locator('#bot-composer').waitFor();
  const freshRoute = new URL(page.url()).hash;
  await send('<img src=x onerror="window.injected=true">');
  await page.clock.runFor(4000);
  assert.equal(await page.evaluate(() => Boolean(window.injected)), false);
  assert.equal(await page.locator('#bot-thread img').count(), 0);
  await page.locator(`[role="tab"][data-tab-id="${settingsRoute.split('/').at(-1)}"]`).click();
  assert.equal(new URL(page.url()).hash, settingsRoute);
  const newThreadId = freshRoute.split('/').at(-1);
  await page.locator(`[role="tab"][data-tab-id="${newThreadId}"]`).click();
  assert.equal(new URL(page.url()).hash, freshRoute);
  await page.goBack();
  await page.locator('#bot-composer').waitFor();
  assert.notEqual(new URL(page.url()).hash, freshRoute);
  await page.goForward();
  assert.equal(new URL(page.url()).hash, freshRoute);

  await page.getByRole('button', { name: 'Toggle theme', exact: true }).click();
  await page.reload();
  await page.locator('#bot-shell').waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.dataset.mode), 'light');
  assert.equal(await page.locator('#bot-sidebar [data-shell-toggle]').count(), 0);
  await page.getByRole('button', { name: 'Add agent', exact: true }).click();
  const addDialog = page.getByRole('dialog');
  assert.equal(await page.evaluate(() => document.activeElement?.name), 'name', 'Add Agent focuses the name input');
  await addDialog.getByRole('textbox', { name: 'Agent name', exact: true }).fill('Nova');
  await addDialog.getByRole('textbox', { name: 'Agent role', exact: true }).fill('Writer');
  await addDialog.getByRole('textbox', { name: 'Agent instructions', exact: true }).fill('Write clear sample copy.');
  await addDialog.getByRole('button', { name: 'Add agent', exact: true }).click();
  await page.getByText('Success add agent', { exact: true }).waitFor();
  assert.equal(await page.locator('[data-bot-agent]').filter({ hasText: 'Nova' }).count(), 0);
  await page.clock.runFor(300);
  assert.equal(await page.locator('#bot-add-agent-dialog').evaluate(dialog => dialog.open), false);
  await page.evaluate(() => { window.originalSidebar = document.getElementById('bot-sidebar'); window.originalShell = document.getElementById('bot-shell'); });
  await page.locator('[data-tree-key="bot-settings"]').click();
  await page.getByRole('heading', { name: 'Agent settings', exact: true }).waitFor();
  assert.ok(await page.evaluate(() => window.originalSidebar === document.getElementById('bot-sidebar') && window.originalShell === document.getElementById('bot-shell')));

  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await page.clock.runFor(500);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No page overflow at ' + width);
    await page.locator('.bot-team-toggle [data-shell-toggle]').click();
    await page.clock.runFor(500);
    await page.locator('[data-tree-key="bot-settings"]').click();
    await page.getByRole('heading', { name: 'Agent settings', exact: true }).waitFor();
    await page.keyboard.press('Escape');
    await page.clock.runFor(500);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Settings fits at ' + width);
  }
  assert.deepEqual(errors, []);
  console.log(`Agent Bot passed (${browserName}): chat, files, retry/stop/recovery, task approval, settings, routing, persistence, narrow layout.`);
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); server.kill(); });
