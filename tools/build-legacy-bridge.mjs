import { readFile, writeFile } from 'node:fs/promises';
const source = await readFile(new URL('../src/components/create-builders.mjs', import.meta.url), 'utf8');
const output = '// Generated by npm run build. Edit src/components/create-builders.mjs instead.\n' +
  source.replace('export function createBuilders', 'const SESAMA_CREATE_BUILDERS = function');
const target = new URL('../src/legacy/component-builders.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Legacy bridge is stale. Run npm run build.');
} else await writeFile(target, output);
