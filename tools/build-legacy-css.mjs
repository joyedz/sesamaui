import {readFile, writeFile} from 'node:fs/promises';
import postcss from 'postcss';

const names = ['button','icon-button','field','select','popup','modal','control'];
const parts = [];
for (const name of names) {
  const source = await readFile(new URL(`../src/styles/components/${name}.css`,import.meta.url),'utf8');
  const ast = postcss.parse(source);
  ast.walkAtRules('import',node => node.remove());
  ast.walkRules(rule => {rule.selector = rule.selector.replaceAll(':where(.sui-root) ','').replaceAll(':where(.sui-root)',':root');});
  parts.push(ast.toString());
}
const output = '/* Generated by npm run build. Edit src/styles/components/*.css instead. */\n' + parts.join('\n');
const target = new URL('../src/styles/legacy-controls.css',import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target,'utf8') !== output) throw Error('Legacy CSS is stale. Run npm run build.');
} else await writeFile(target,output);
